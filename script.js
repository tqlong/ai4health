function translateCommitteeName(name, lang) {
  if (lang !== "en") return name;
  return name
    .replace(/^PGS\.?\s*TS\.?\s*/i, "Assoc. Prof. Dr. ")
    .replace(/^GS\.?\s*TS\.?\s*/i, "Prof. Dr. ")
    .replace(/^TS\.?\s*BS\.?\s*/i, "Dr. ")
    .replace(/^TS\.?\s*/i, "Dr. ")
    .replace(/^ThS\.?\s*/i, "MSc. ");
}

function translateCommitteeAffiliation(affiliation, lang) {
  if (lang !== "en") return affiliation;
  return COMMITTEE_AFFILIATION_EN[affiliation] || affiliation;
}

function translateCommitteeRole(role, lang) {
  if (lang !== "en") return role;
  return COMMITTEE_ROLE_EN[role] || role;
}

let savedLanguage = "vi";
try {
  savedLanguage = localStorage.getItem("ai4health-lang") || "vi";
} catch {
  // The language switch still works when browser storage is unavailable.
}
const state = { lang: Object.hasOwn(I18N, savedLanguage) ? savedLanguage : "vi" };

function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}

function renderCards(containerId, items, labelForIndex) {
  const container = document.getElementById(containerId);
  container.replaceChildren();
  items.forEach((item, index) => {
    const card = el("article", "info-card");
    card.append(el("span", "number", String(index + 1)));
    if (labelForIndex) card.append(el("p", "topic-kind", labelForIndex(index)));
    card.append(el("h3", "", item.title || item));
    if (item.text) card.append(el("p", "", item.text));
    container.append(card);
  });
}

function renderProgram(lang) {
  const container = document.getElementById("programGrid");
  container.replaceChildren();
  CONTENT[lang].program.forEach((day) => {
    const article = el("article", "program-day");
    article.append(el("h3", "", day.title));
    article.append(el("p", "", day.note));
    const list = el("div", "session-list");
    day.sessions.forEach(([time, title, text]) => {
      const session = el("div", "session");
      session.append(el("time", "", time));
      session.append(el("strong", "", title));
      if (text) session.append(el("p", "", text));
      list.append(session);
    });
    article.append(list);
    container.append(article);
  });
}

function renderRequirements(lang) {
  const container = document.getElementById("cfpRequirements");
  container.replaceChildren();
  CONTENT[lang].requirements.forEach((block) => {
    const article = el("article", "requirement-block");
    article.append(el("h3", "", block.title));
    const list = el("ul");
    block.items.forEach((item) => list.append(el("li", "", item)));
    article.append(list);
    container.append(article);
  });
}

function renderCommittees(lang) {
  const container = document.getElementById("committeesList");
  const labels = CONTENT[lang].table;
  container.replaceChildren();
  COMMITTEES.forEach((committee, index) => {
    const details = el("details", "committee-panel");
    if (index === 0) details.open = true;
    const summary = el("summary");
    summary.append(el("strong", "", committee.title[lang]));
    summary.append(el("span", "", `${committee.members.length} ${I18N[lang].memberLabel}`));
    details.append(summary);

    const wrap = el("div", "committee-table-wrap");
    const table = el("table");
    const thead = el("thead");
    const headRow = el("tr");
    [labels.name, labels.affiliation, labels.role].forEach((label) => headRow.append(el("th", "", label)));
    thead.append(headRow);
    table.append(thead);

    const tbody = el("tbody");
    committee.members.forEach(([name, affiliation, role]) => {
      const row = el("tr");
      row.append(el("td", "", translateCommitteeName(name, lang)));
      row.append(el("td", "", translateCommitteeAffiliation(affiliation, lang)));
      row.append(el("td", "", translateCommitteeRole(role, lang)));
      tbody.append(row);
    });
    table.append(tbody);
    wrap.append(table);
    details.append(wrap);
    container.append(details);
  });
}

function render(lang) {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    node.textContent = I18N[lang][key] || I18N.en[key] || "";
  });
  ["aria-label", "alt", "content", "href"].forEach((attribute) => {
    document.querySelectorAll(`[data-i18n-${attribute}]`).forEach((node) => {
      const key = node.getAttribute(`data-i18n-${attribute}`);
      node.setAttribute(attribute, I18N[lang][key] || I18N.en[key] || "");
    });
  });
  document.querySelectorAll(".lang-btn").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.lang === lang);
    button.setAttribute("aria-pressed", String(button.dataset.lang === lang));
  });
  renderCards("objectives", CONTENT[lang].objectives);
  renderCards("topicsGrid", CONTENT[lang].topics, () => I18N[lang].topicLabel);
  renderCards("deliverablesGrid", CONTENT[lang].deliverables);
  renderProgram(lang);
  renderRequirements(lang);
  renderCommittees(lang);
}

document.querySelectorAll(".lang-btn").forEach((button) => {
  button.addEventListener("click", () => {
    state.lang = button.dataset.lang;
    try {
      localStorage.setItem("ai4health-lang", state.lang);
    } catch {
      // Apply the selection even if it cannot be saved.
    }
    render(state.lang);
  });
});

const navToggle = document.querySelector(".nav-toggle");
const siteNav = document.querySelector(".site-nav");

function closeMenu() {
  document.body.classList.remove("menu-open");
  navToggle.setAttribute("aria-expanded", "false");
}

navToggle.addEventListener("click", () => {
  const open = !document.body.classList.contains("menu-open");
  document.body.classList.toggle("menu-open", open);
  navToggle.setAttribute("aria-expanded", String(open));
});

document.querySelectorAll(".site-nav a").forEach((link) => {
  link.addEventListener("click", closeMenu);
});

document.addEventListener("click", (event) => {
  if (!document.body.classList.contains("menu-open")) return;
  if (navToggle.contains(event.target) || siteNav.contains(event.target)) return;
  closeMenu();
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && document.body.classList.contains("menu-open")) {
    closeMenu();
    navToggle.focus();
  }
});

